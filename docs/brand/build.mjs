async function shoot(url, file, width, height, fullPage = true) {
  const page = await context.newPage();
  await page.setViewportSize({ width, height });
  await page.goto(url, { waitUntil: "networkidle" });
  await page.evaluate(() => document.fonts.ready);
  const loaded = await page.evaluate(() => [...document.fonts].filter((f) => f.status === "loaded").map((f) => f.family));
  if (!loaded.some((f) => /Manrope/.test(f))) console.warn("Warning: web fonts did not load; screenshots use fallback fonts. Try FONTS_VIA_CURL=1.");
  await page.screenshot({ path: out(file), fullPage });
  await page.close();
}
