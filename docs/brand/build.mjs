const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const lum = (h) => {
  const [r, g, b] = rgb(h).map((v) => v / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
export const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return Math.round(((x + 0.05) / (y + 0.05)) * 100) / 100;
};
const grade = (r, kind) => {
  if (kind === "decorative") return { label: "Decorative only", ok: null };
  if (kind === "ui") return r >= 3 ? { label: "Pass 3:1", ok: true } : { label: "Fail", ok: false };
  if (r >= 7) return { label: "AAA", ok: true };
  if (r >= 4.5) return { label: "AA", ok: true };
  if (r >= 3) return { label: "AA large only", ok: null };
  return { label: "Fail", ok: false };
};
const kebab = (s) => (s.charAt(0).toLowerCase() + s.slice(1)).replace(/[A-Z]/g, (m) => "-" + m.toLowerCase());

